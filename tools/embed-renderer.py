#!/usr/bin/env python3
"""Generate a self-contained inline renderer below SDK's 512 KiB HTML limit."""
import base64
import json
import re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def uri(path,mime):
    return 'data:'+mime+';base64,'+base64.b64encode(path.read_bytes()).decode('ascii')
def generate():
    import runpy
    runpy.run_path(str(root/'tools/embed-mdi.py'),run_name='__main__')
    runpy.run_path(str(root/'tools/embed-custom-icons.py'),run_name='__main__')
    folder=root/'assets/clock'
    html=(folder/'index.html').read_text(encoding='utf-8')
    html=html.replace('fonts/Outfit.ttf',uri(folder/'fonts/Outfit.ttf','font/ttf'))
    js=(folder/'clock.js').read_text(encoding='utf-8')
    icons={p.stem:uri(p,'image/svg+xml') for p in (folder/'weather-icons').glob('*.svg')}
    js=js.replace("'weather-icons/' + icon + '.svg'",'inlineIcons[icon]')
    script='window.clockOptions=%CLOCK_OPTIONS_JSON%;\nconst inlineIcons='+json.dumps(icons)+';\n'+js
    assert not re.search(r'</script',script,re.I)
    html=html.replace('<script src="clock.js"></script>','<script>'+script+'</script>')
    assert len(html.encode('utf-8'))+32768<524288
    chunks=[html[i:i+12000] for i in range(0,len(html),12000)]
    source='// Generated by tools/embed-renderer.py; edit assets/clock instead.\npackage pl.piotrek.kiosk;\nfinal class InlineRenderer {\n'
    source+=' static String html(String json) {\n  StringBuilder result=new StringBuilder();\n'
    for chunk in chunks:
        source+='  result.append('+json.dumps(chunk,ensure_ascii=True)+');\n'
    source+='  return result.toString().replace("%CLOCK_OPTIONS_JSON%",json);\n }\n}\n'
    (root/'src/pl/piotrek/kiosk/InlineRenderer.java').write_text(source,encoding='utf-8')
    print(f'Inline renderer: {len(html.encode("utf-8"))} bytes before configuration')
    return html
if __name__=='__main__': generate()
