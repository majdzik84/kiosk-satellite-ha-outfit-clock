"""Embed a compressed MDI catalog in Java; only selected paths enter inline HTML."""
import base64
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def generate():
    data=base64.b64encode((root/'resources/mdi/paths.tsv.gz').read_bytes()).decode()
    source='// Generated by tools/embed-mdi.py. MDI icons: Apache-2.0.\npackage pl.piotrek.kiosk;\n'
    source+='final class MdiData { static String encoded() { StringBuilder s=new StringBuilder();\n'
    for i in range(0,len(data),12000): source+='s.append("'+data[i:i+12000]+'");\n'
    source+='return s.toString(); } }\n'
    (root/'src/pl/piotrek/kiosk/MdiData.java').write_text(source)
if __name__=='__main__': generate()
